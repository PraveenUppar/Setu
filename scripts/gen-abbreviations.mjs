/**
 * Generate lib/document/sections/abbreviations.ts from the extracted fixture.
 *
 * Abbreviations are the ONE part of a prospectus glossary that is safe to
 * carry across issuers wholesale: an expansion ("AGM" -> "Annual General
 * Meeting") contains no issuer facts by construction. Contrast D21, where the
 * definitions proper had to be authored one at a time because issuer specifics
 * hid inside them as bare numbers and codes.
 *
 * The check is still run rather than assumed — see SUSPICIOUS below.
 *
 * Usage: node scripts/gen-abbreviations.mjs
 */
import fs from 'node:fs';

const raw = JSON.parse(fs.readFileSync('fixtures/definitions/abbreviations.json', 'utf8'));

/* Merge rows where the abbreviation column wrapped. */
const merged = [];
for (const p of raw) {
  const prev = merged[merged.length - 1];
  const prevWrapped = prev && /[a-z/]$/.test(prev.a) && prev.a.length > 18;
  if (prev && prevWrapped && p.a.length < 24 && /^[A-Z][a-z]/.test(p.a)) {
    prev.a = `${prev.a} ${p.a}`.replace(/\s+/g, ' ').trim();
    prev.f = `${prev.f} ${p.f}`.replace(/\s+/g, ' ').trim();
  } else {
    merged.push({ a: p.a.replace(/\s+/g, ' ').trim(), f: p.f.replace(/\s+/g, ' ').trim() });
  }
}

/* Anything naming the source issuer, its people, its advisers or its codes. */
const SUSPICIOUS =
  /Om Galaxy|OMG|Baddhan|Opinder|Jyothish|Sathyapalan|Mumbai II|124851W|INE[0-9A-Z]{9}|Blue Chip|Sativali|Shetty Naik/i;

/**
 * The page range also contains the KEY PERFORMANCE INDICATOR table, whose rows
 * look superficially similar but are calculation definitions ("EBITDA is
 * calculated as Restated Earnings before...", "RoCE refers to..."). Those
 * belong with Basis for Issue Price, not the abbreviations, and several are
 * phrased around "the Company" in ways that need fact substitution.
 *
 * Excluded here rather than silently mixed in.
 */
const IS_KPI_DEFINITION = /\b(is calculated as|refers to (the )?(Restated|ratio)|is the ratio of|divided by)\b/i;

const clean = [];
const flagged = [];
for (const p of merged) {
  if (p.a.length < 1 || p.a.length > 34 || p.f.length < 3) continue;
  if (!/^[A-Za-z]/.test(p.a)) continue; // footnote markers such as "- ()"
  if (p.f.length > 220 || IS_KPI_DEFINITION.test(p.f)) continue; // KPI table
  if (SUSPICIOUS.test(`${p.a} ${p.f}`)) flagged.push(p);
  else clean.push(p);
}

if (flagged.length > 0) {
  console.error('REFUSING TO GENERATE - issuer-specific content found:');
  for (const p of flagged) console.error(`  ${p.a} -> ${p.f}`);
  process.exit(1);
}

/* Dedupe, keeping the first (fuller) definition of any repeated abbreviation. */
const seen = new Set();
const unique = clean.filter((p) => {
  const k = p.a.toLowerCase();
  if (seen.has(k)) return false;
  seen.add(k);
  return true;
});
unique.sort((x, y) => x.a.localeCompare(y.a, 'en'));

const esc = (s) => s.replace(/\\/g, '\\\\').replace(/'/g, "\\'");

const out = `import type { Definition } from './definitions';

/**
 * Conventional terms and abbreviations.
 *
 * GENERATED by scripts/gen-abbreviations.mjs from
 * fixtures/definitions/abbreviations.json. Do not edit by hand — re-run the
 * generator.
 *
 * These are the one part of a prospectus glossary safe to carry across issuers
 * wholesale: an expansion contains no issuer facts by construction. The
 * definitions proper had to be authored individually (D21) because issuer
 * specifics hid inside them as bare numbers and registration codes. The
 * generator still checks, and refuses to emit if it finds any.
 *
 * Source: Om Galaxy RHP pp.18-24, ${unique.length} entries.
 */
export const ABBREVIATIONS: Definition[] = [
${unique
  .map(
    (p) => `  {
    term: '${esc(p.a)}',
    kind: 'standard',
    describe: () => '${esc(p.f)}',
  },`,
  )
  .join('\n')}
];
`;

fs.writeFileSync('lib/document/sections/abbreviations.ts', out);
console.log(`generated ${unique.length} abbreviations -> lib/document/sections/abbreviations.ts`);
